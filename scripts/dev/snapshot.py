#!/usr/bin/env python3
"""Plan, refresh, or use detached snapshots of the nine FAST-HEP packages."""

from __future__ import annotations

import argparse
import json
import os
import re
import shlex
import subprocess
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path

MODULES = {
    "flow": "hepflow",
    "distributed": "fasthep_distributed",
    "carpenter": "fasthep_carpenter",
    "curator": "fasthep_curator",
    "render": "fasthep_render",
    "cli": "fasthep_cli",
    "toolbench": "fasthep_toolbench",
    "workshop": "fasthep_workshop",
    "fasthep": "fasthep",
}
WORKTREES = Path("build/worktrees")
VERSION_HEADER = "# Generated by scripts/dev/snapshot.py\n"
COLUMNS = ("REPO", "REF", "OLD TIP", "NEW TIP", "BEHIND", "ACTION")
LEGEND = """\
REF is the selected branch. BEHIND counts commits on that branch missing from the old tip.
create: new detached snapshot; move: refresh an existing snapshot; current: tip unchanged.
override: use the requested branch; skip: dirty: keep local changes; fail: repository error."""

IMPORT_CHECK = """\
import importlib
import json
import sys
from pathlib import Path

paths, packages = json.loads(sys.argv[1])
sys.path[:0] = paths
for module, directory in packages.items():
    filename = getattr(importlib.import_module(module), "__file__", None)
    expected = Path(directory)
    if filename is None or not Path(filename).resolve().is_relative_to(expected):
        raise SystemExit(f"{module}: {filename} resolves outside {expected}")
    print(f"{module}: {Path(filename).resolve()}", file=sys.stderr)
"""


def git(directory: Path, *args: str, check: bool = True) -> str:
    result = subprocess.run(
        ["git", "-C", str(directory), *args],
        env={**os.environ, "GIT_WORK_TREE": str(directory)},
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode and check:
        raise RuntimeError(
            f"git {' '.join(args)} in {directory}: {result.stderr.strip()}"
        )
    return result.stdout.rstrip("\n") if result.returncode == 0 else ""


def guess_version(describe: str) -> str:
    match = re.fullmatch(r"(.+)-(\d+)-(g[0-9a-f]+)", describe)
    if not match:
        return describe
    tag, distance, commit = match.groups()
    if distance == "0":
        return tag
    prefix, patch = tag.rsplit(".", 1)
    return f"{prefix}.{int(patch) + 1}.dev{distance}+{commit}"


def write_version_file(snapshot: Path) -> str:
    config = tomllib.loads((snapshot / "pyproject.toml").read_text(encoding="utf-8"))
    hatch = config["tool"]["hatch"]
    relative = hatch["build"]["hooks"]["vcs"]["version-file"]
    target = snapshot / relative
    if (
        not target.resolve().is_relative_to(snapshot)
        or target.name != "_version.py"
        or target.is_symlink()
        or git(snapshot, "ls-files", "--", relative)
        or not git(snapshot, "check-ignore", "--", relative, check=False)
    ):
        raise ValueError(f"refusing to generate version at {target}")
    describe = git(snapshot, "describe", "--tags", "--long", "--always", "HEAD")
    if re.fullmatch(r"[0-9a-f]+", describe):
        version = hatch["version"]["raw-options"]["fallback_version"]
        commit_id = f"g{describe}"
    else:
        version = guess_version(describe)
        commit_id = describe.rsplit("-", 1)[-1]
    public, _, local = version.partition("+")
    parts = tuple(int(part) if part.isdecimal() else part for part in public.split("."))
    if local:
        parts += (local,)
    contents = (
        VERSION_HEADER + f"__version__ = version = {version!r}\n"
        f"__version_tuple__ = version_tuple = {parts!r}\n"
        f"__commit_id__ = commit_id = {commit_id!r}\n"
    )
    if target.exists():
        if not target.is_file() or target.stat().st_nlink != 1:
            raise ValueError(f"refusing to overwrite {target}")
        previous = target.read_text(encoding="utf-8")
        if previous == contents:
            return "version unchanged"
        if not previous.startswith(VERSION_HEADER):
            raise ValueError(
                f"refusing to overwrite an existing version file: {target}"
            )
    target.write_text(contents, encoding="utf-8")
    return f"version {version}"


@dataclass
class Snapshot:
    root: Path
    name: str
    ref: str = "-"
    old: str = ""
    new: str = ""
    behind: str = "-"
    action: str = ""

    @property
    def repo(self) -> Path:
        return self.root / self.name

    @property
    def path(self) -> Path:
        return self.root / WORKTREES / f"snapshot-{self.name}"

    def row(self) -> tuple[str, ...]:
        return (
            self.name,
            self.ref,
            self.old[:8] or "-",
            self.new[:8] or "-",
            self.behind,
            self.action,
        )


def common_dir(path: Path) -> str:
    return git(path, "rev-parse", "--path-format=absolute", "--git-common-dir")


def check_repo(repo: Path) -> None:
    if not (repo / ".git").exists() or repo.is_symlink():
        raise RuntimeError(f"missing package checkout: {repo}")


def existing_head(item: Snapshot) -> str:
    path = item.path
    if path.resolve() != path:
        raise RuntimeError(f"refusing a symlink in snapshot path: {path}")
    listing = git(item.repo, "worktree", "list", "--porcelain", "-z")
    registered = f"worktree {path}" in listing.split("\0")
    if not path.exists():
        if registered:
            raise RuntimeError(f"registered snapshot is missing: {path}")
        return ""
    if (
        not registered
        or not (path / ".git").is_file()
        or common_dir(path) != common_dir(item.repo)
    ):
        raise RuntimeError(f"path is not a worktree of {item.name}: {path}")
    return git(path, "rev-parse", "HEAD")


def default_ref(repo: Path) -> str:
    return git(repo, "symbolic-ref", "-q", "refs/remotes/origin/HEAD", check=False) or (
        "refs/remotes/origin/main"
    )


def resolve_commit(repo: Path, ref: str, *, check: bool = True) -> str:
    return git(
        repo,
        "rev-parse",
        "--verify",
        "--end-of-options",
        f"{ref}^{{commit}}",
        check=check,
    )


def behind_count(repo: Path, old: str, new: str) -> str:
    return git(repo, "rev-list", "--count", f"{old}..{new}")


def plan(item: Snapshot, override: str | None, *, fetch: bool) -> None:
    check_repo(item.repo)
    if fetch:
        git(item.repo, "fetch", "--quiet", "--no-prune", "--no-prune-tags", "origin")
    ref = default_ref(item.repo)
    if override is not None:
        branch_ref = f"refs/heads/{override}"
        if (
            git(item.repo, "check-ref-format", "--normalize", branch_ref, check=False)
            != branch_ref
        ):
            raise ValueError(f"invalid branch name: {override}")
        ref = f"refs/remotes/origin/{override}"
        if not resolve_commit(item.repo, ref, check=False):
            ref = branch_ref
    item.ref = ref.removeprefix("refs/remotes/").removeprefix("refs/heads/")
    item.new = resolve_commit(item.repo, ref)
    item.old = existing_head(item)
    if not item.old:
        item.action = "create"
    else:
        item.behind = behind_count(item.repo, item.old, item.new)
        if dirty(item.path):
            item.action = "skip: dirty"
            return
        attached = git(item.path, "symbolic-ref", "-q", "HEAD", check=False)
        item.action = "current" if item.old == item.new and not attached else "move"
        if item.old != item.new and override is None:
            item.action += " (moves from override or earlier default tip)"
    if override is not None:
        item.action = f"override ({item.action})"


def dirty(path: Path) -> bool:
    return bool(git(path, "status", "--porcelain", "--untracked-files=all"))


def execute(item: Snapshot) -> None:
    if item.action == "skip: dirty":
        return
    if existing_head(item) != item.old:
        raise RuntimeError("snapshot changed while planning; retry")
    if item.old:
        if dirty(item.path):
            item.action = "skip: dirty"
            return
        if item.action not in ("current", "override (current)"):
            git(item.path, "checkout", "--detach", "--no-overwrite-ignore", item.new)
    else:
        git(item.repo, "worktree", "add", "--detach", str(item.path), item.new)
    item.action += f"; {write_version_file(item.path)}"


def table(items: list[Snapshot]) -> str:
    rows = [COLUMNS, *(item.row() for item in items)]
    widths = [max(map(len, column)) for column in zip(*rows)]
    rows.insert(1, tuple("-" * width for width in widths))
    return "\n".join(
        "  ".join(cell.ljust(width) for cell, width in zip(row, widths)).rstrip()
        for row in rows
    )


def environment(
    root: Path, repos: list[str], *, require_fresh: bool
) -> tuple[dict, dict]:
    packages = {}
    paths = []
    for name, module in MODULES.items():
        item = Snapshot(root, name)
        check_repo(item.repo)
        if name in repos:
            head = existing_head(item)
            if not head:
                raise RuntimeError(
                    f"missing snapshot: {item.path}; run snapshot --execute"
                )
            latest = resolve_commit(item.repo, default_ref(item.repo))
            count = behind_count(item.repo, head, latest)
            if count != "0":
                message = f"{name}: snapshot is {count} behind {default_ref(item.repo)}"
                if require_fresh:
                    raise RuntimeError(message)
                print(f"warning: {message}", file=sys.stderr)
            checkout, label = item.path, "snapshot"
        else:
            checkout, label = item.repo, "workspace checkout"
        source = checkout / "src"
        packages[module] = str(source / module)
        paths.append(str(source))
        print(f"{name}: {label} ({source})", file=sys.stderr)
    inherited = os.environ.get("PYTHONPATH")
    if inherited:
        paths.append(inherited)
    dev_bin = root / ".pixi/envs/dev/bin"
    variables = {
        "PYTHONPATH": os.pathsep.join(paths),
        "PATH": os.pathsep.join([str(dev_bin), os.environ.get("PATH", os.defpath)]),
    }
    return variables, packages


def add_selection(parser: argparse.ArgumentParser) -> None:
    parser.add_argument(
        "--root", type=Path, default=Path.cwd(), help="workspace root (default: cwd)"
    )
    parser.add_argument(
        "--repo", choices=MODULES, action="append", help="select a package (repeatable)"
    )


def environment_main(mode: str, argv: list[str]) -> int:
    parser = argparse.ArgumentParser(prog=f"snapshot {mode}")
    add_selection(parser)
    parser.add_argument("--require-fresh", action="store_true")
    if mode == "env":
        parser.add_argument("--json", action="store_true")
    else:
        parser.add_argument(
            "--cwd", type=Path, help="command directory (default: workspace root)"
        )
        parser.add_argument("command", nargs=argparse.REMAINDER)
    args = parser.parse_args(argv)
    if mode == "run":
        # Pixi consumes the separator when forwarding task arguments.
        if args.command[:1] == ["--"]:
            args.command.pop(0)
        if not args.command:
            parser.error("run needs a command")
    root = args.root.resolve()
    try:
        variables, packages = environment(
            root, args.repo or list(MODULES), require_fresh=args.require_fresh
        )
        if mode == "env":
            if args.json:
                print(json.dumps(variables))
            else:
                print(f"export PYTHONPATH={shlex.quote(variables['PYTHONPATH'])}")
                dev_bin = shlex.quote(str(root / ".pixi/envs/dev/bin"))
                print(f'export PATH={dev_bin}:"$PATH"')
        else:
            cwd = (args.cwd or root).resolve()
            env = {**os.environ, **variables}
            python = root / ".pixi/envs/dev/bin/python"
            paths = variables["PYTHONPATH"].split(os.pathsep)
            if not env.get("PYTHONSAFEPATH"):
                paths.insert(0, str(cwd))
            payload = json.dumps([paths, packages])
            subprocess.run(
                [str(python), "-I", "-c", IMPORT_CHECK, payload],
                env=env,
                cwd=cwd,
                stdout=sys.stderr,
                check=True,
            )
            os.chdir(cwd)
            os.execvpe(args.command[0], args.command, env)
    except (OSError, RuntimeError, subprocess.CalledProcessError) as error:
        print(f"snapshot {mode}: {error}", file=sys.stderr)
        return 1
    return 0


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    if argv and argv[0] in ("env", "run"):
        return environment_main(argv[0], argv[1:])

    parser = argparse.ArgumentParser(
        description=__doc__, epilog="Subcommands: env, run -- COMMAND"
    )
    add_selection(parser)
    parser.add_argument("--use", action="append", default=[], metavar="REPO=REF")
    parser.add_argument("--no-fetch", action="store_true")
    parser.add_argument(
        "--execute", action="store_true", help="apply the plan (default: dry run)"
    )
    args = parser.parse_args(argv)
    repos = args.repo or list(MODULES)
    overrides = {}
    for spec in args.use:
        name, separator, ref = spec.partition("=")
        if name not in repos or name in overrides or not separator or not ref:
            parser.error(f"expected one --use REPO=REF per selected repo; got {spec!r}")
        overrides[name] = ref

    root = args.root.resolve()
    items = [Snapshot(root, name) for name in MODULES if name in repos]
    for item in items:
        try:
            plan(item, overrides.get(item.name), fetch=not args.no_fetch)
            if args.execute:
                execute(item)
        except (OSError, RuntimeError, ValueError, KeyError) as error:
            item.action = f"fail: {error}"
    print(table(items))
    print(f"\n{LEGEND}")
    if not args.execute:
        print("Dry run. Add --execute to create or refresh snapshots.")
    return int(any(item.action.startswith("fail:") for item in items))


if __name__ == "__main__":
    raise SystemExit(main())
